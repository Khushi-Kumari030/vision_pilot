import cv2
import numpy as np

img = cv2.imread("frame_50.jpg")

lane0 = np.array([
    (83,59),(81,60),(79,61),(78,62),(103,63),
    (114,64),(105,65),(73,66),(72,67),(71,68),
    (68,69),(66,70),(61,71),(58,72),(56,73),
    (57,74),(55,75),(53,76),(49,77),(46,78),(45,79)
], dtype=np.int32)

lane1 = np.array([
    (89,57),(89,58),(89,59),(90,60),(90,61),
    (92,62),(106,63),(117,64),(120,65),(114,66),
    (105,67),(107,68),(122,69),(125,70),(127,71),
    (129,72),(128,73),(130,74),(131,75),(132,76),
    (133,77),(126,78),(125,79)
], dtype=np.int32)

for lane, color in [(lane0,(0,255,0)), (lane1,(0,0,255))]:

    x = lane[:,0]
    y = lane[:,1]

    m, c = np.polyfit(y, x, 1)

    y1 = 480
    y2 = 250

    x1 = int(m*y1 + c)
    x2 = int(m*y2 + c)

    cv2.line(
        img,
        (x1,y1),
        (x2,y2),
        color,
        4
    )

cv2.imshow("Lane Fitting",img)
cv2.waitKey(0)
cv2.destroyAllWindows()